"""Draw the site's illustrations: one per tab, one per project.

Every drawing shares the same paper, ink, palette and hand-drawn wobble, so
they read as one hand. The wobble is an feTurbulence displacement over plain
strokes; nothing here is traced or generated by a model.

    python3 scripts/draw-art.py      # writes static/img/art/**.svg
"""

