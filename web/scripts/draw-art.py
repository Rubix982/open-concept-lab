def svg(label: str, wash: str, body: str, seed: int, wash_at: tuple[int, int] = (300, 210)) -> str:
    """A drawing on paper: grain, a soft wash of colour, then the wobbly ink."""
    cx, cy = wash_at
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" role="img" aria-label="{label}">
  <defs>
    <filter id="rough" x="-5%" y="-5%" width="110%" height="110%">
      <feTurbulence type="fractalNoise" baseFrequency="0.034" numOctaves="2" seed="{seed}"/>
      <feDisplacementMap in="SourceGraphic" scale="3"/>
    </filter>
    <filter id="grain"><feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="1" seed="{seed + 1}"/><feColorMatrix values="0 0 0 0 0.35  0 0 0 0 0.3  0 0 0 0 0.2  0 0 0 0.05 0"/></filter>
  </defs>
  <rect width="{W}" height="{H}" fill="{PAPER}"/>
  <rect width="{W}" height="{H}" filter="url(#grain)"/>
  <ellipse cx="{cx}" cy="{cy}" rx="220" ry="150" fill="{wash}" opacity="0.24"/>
  <g filter="url(#rough)" fill="none" stroke="{INK}" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round">
{body}
  </g>
</svg>
"""


