def built() -> str:
    def brick(x: int, y: int, colour: str) -> str:
        return (
            f'<rect x="{x}" y="{y}" width="64" height="36" rx="4" fill="{colour}" fill-opacity="0.85"/>'
            f'<rect x="{x + 10}" y="{y - 8}" width="14" height="8" rx="2" fill="{colour}"/>'
            f'<rect x="{x + 40}" y="{y - 8}" width="14" height="8" rx="2" fill="{colour}"/>'
        )

    stacks = [(150, 1, SALMON), (230, 3, INDIGO), (310, 2, SAGE), (390, 4, GOLD)]
    bricks = []
    for x, n, colour in stacks:
        for i in range(n):
            bricks.append(brick(x, 300 - 36 * (i + 1) + 6, colour))
    body = "\n    ".join(bricks) + f"""
    <path d="M120 306 H490" stroke-width="2.6"/>
    <path d="M480 80 V140 M470 80 H520 M500 80 V100" stroke-width="2"/>
    <path d="M500 100 q-8 12 0 18" stroke-width="2"/>"""
    return svg("Toy bricks stacked into a bar chart, a small crane over them: pages built to understand something", INDIGO, body, 13)


