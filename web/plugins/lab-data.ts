const DATED_FILE = /^(\d{4})-(\d{2})-(\d{2})-(.+)\.mdx?$/;

async function readYaml<T>(file: string): Promise<T | undefined> {
  try {
    return parseYaml(await fs.readFile(file, "utf8")) as T;
  } catch {
    return undefined;
  }
}

async function loadWriting(
  blogDir: string,
  routeBasePath: string,
): Promise<WritingEntry[]> {
  let files: string[] = [];
  try {
    files = await fs.readdir(blogDir);
  } catch {
    return [];
  }

  const entries = await Promise.all(
    files
      .map((file) => ({ file, match: DATED_FILE.exec(file) }))
      .filter(
        (c): c is { file: string; match: RegExpExecArray } => c.match !== null,
      )
      .map(async ({ file, match }): Promise<WritingEntry | null> => {
        const [, year, month, day, name] = match;
        const fileContent = await fs.readFile(path.join(blogDir, file), "utf8");
        const { frontMatter, content } = await parseMarkdownFile({
          filePath: file,
          fileContent,
          parseFrontMatter: DEFAULT_PARSE_FRONT_MATTER,
        });
        const fm = frontMatter as Record<string, unknown>;
        // Docusaurus hides drafts from a production build; the list has to agree
        // or the switcher links to a page that does not exist.
        if (fm.draft === true && process.env.NODE_ENV === "production") {
          return null;
        }
        const slug =
          typeof fm.slug === "string" && fm.slug.length > 0 ? fm.slug : name;

        return {
          title: typeof fm.title === "string" ? fm.title : slug,
          slug,
          permalink: `/${routeBasePath}/${slug.replace(/^\//, "")}`,
          date:
            typeof fm.date === "string" ? fm.date : `${year}-${month}-${day}`,
          summary:
            (typeof fm.standfirst === "string" && fm.standfirst) ||
            (typeof fm.description === "string" && fm.description) ||
            createExcerpt(content) ||
            "",
          status: typeof fm.status === "string" ? fm.status : undefined,
          project: typeof fm.project === "string" ? fm.project : undefined,
          tags: Array.isArray(fm.tags)
            ? fm.tags.filter((t): t is string => typeof t === "string")
            : [],
          words: countWords(content),
          notes: (content.match(/<(Claude|Gloss)\b/g) ?? []).length,
        } satisfies WritingEntry;
      }),
  );

  const kept = entries.filter((e): e is WritingEntry => e !== null);
  kept.sort((a, b) => (a.date < b.date ? 1 : -1));
  return kept;
}

/** Words of prose: code blocks, JSX, comments and link targets don't count. */
function countWords(markdown: string): number {
  const prose = markdown
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\]\([^)]*\)/g, "]")
    .replace(/[#*_`>\[\]|-]/g, " ");
  return prose.split(/\s+/).filter((w) => /[\p{L}\p{N}]/u.test(w)).length;
}

/** Markdown emphasis and code spans read as noise in a table cell. */
function stripMarkdown(text: string): string {
  return text
    .replace(/`([^`]*)`/g, "$1")
    .replace(/\*\*([^*]*)\*\*/g, "$1")
    .replace(/\*([^*]*)\*/g, "$1")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/** The first paragraph under a `## Heading`, as one line. */
function sectionParagraph(markdown: string, heading: string): string {
  const section = markdown.split(new RegExp(`^## ${heading}\\s*$`, "m"))[1];
  if (!section) {
    return "";
  }
  const body = section.split(/^## /m)[0] ?? "";
  const paragraph = body.trim().split(/\n\s*\n/)[0] ?? "";
  return stripMarkdown(paragraph);
}

const ABBREVIATIONS = ["e.g", "i.e", "cf", "vs", "et al", "Fig", "eq"];

/**
 * Trims to whole sentences rather than mid-clause. Splits only on a period
 * outside parentheses that does not end a known abbreviation, then keeps
 * sentences while under the soft limit — always at least one, so a single
 * long sentence survives intact rather than being cut.
 */
function summarize(text: string, softLimit: number): string {
  if (text.length <= softLimit) {
    return text;
  }

  const sentences: string[] = [];
  let depth = 0;
  let start = 0;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === "(" || ch === "[") depth += 1;
    else if (ch === ")" || ch === "]") depth = Math.max(0, depth - 1);
    else if (ch === "." && depth === 0 && (text[i + 1] === " " || i === text.length - 1)) {
      const preceding = text.slice(start, i);
      const endsAbbreviation = ABBREVIATIONS.some((a) => preceding.endsWith(a));
      if (!endsAbbreviation) {
        sentences.push(text.slice(start, i + 1).trim());
        start = i + 1;
      }
    }
  }
  const tail = text.slice(start).trim();
  if (tail.length > 0) {
    sentences.push(tail);
  }

  const kept: string[] = [];
  for (const sentence of sentences) {
    if (kept.length > 0 && [...kept, sentence].join(" ").length > softLimit) {
      break;
    }
    kept.push(sentence);
  }
  return kept.join(" ");
}

/**
 * "Phase 2 — Implementation (reframed project: does…)" carries a short label
 * and then a paragraph of detail. The label is what belongs in a status
 * column; the rest becomes the hover text.
 */
function phaseLabel(phase: string): string {
  const label = phase.split(/[.(]/)[0]?.trim() ?? phase;
  return label.length > 0 ? label : phase;
}

async function loadProjects(
  repoRoot: string,
  entries: {
    name: string;
    plan: string;
    notebook: string;
    tone?: string;
    what?: string;
  }[],
): Promise<Project[]> {
  return Promise.all(
    entries.map(async (entry) => {
      let markdown = "";
      try {
        markdown = await fs.readFile(path.resolve(repoRoot, entry.plan), "utf8");
      } catch {
        // A plan that has moved should be visible, not silently blank.
        return {
          name: entry.name,
          phase: "plan not found",
          phaseDetail: `Could not read ${entry.plan}`,
          what: entry.what ?? "",
          notebook: entry.notebook,
          tone: entry.tone ?? "draft",
        } satisfies Project;
      }

      const phaseDetail = sectionParagraph(markdown, "Current Phase");
      const objective = sectionParagraph(markdown, "Objective");
      const updated = /_Last updated:\s*(\d{4}-\d{2}-\d{2})/.exec(markdown);

      return {
        name: entry.name,
        phase: phaseLabel(phaseDetail),
        phaseDetail,
        what: entry.what ?? summarize(objective, 200),
        updated: updated?.[1],
        notebook: entry.notebook,
        tone: entry.tone ?? "draft",
      } satisfies Project;
    }),
  );
}

const CHECKLIST_PATH = "projects/opz/labs/CHECKLIST.md";
const CHECKLIST_URL =
  "https://github.com/Rubix982/open-concept-lab/blob/main/" + CHECKLIST_PATH;
const KIND_TAG = /`\[(build|design|cloud|GPU)\]`/g;

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

/**
 * Just enough inline markdown for a checklist line: code, bold, italic, links.
 * Relative links point at lab folders, so they resolve against the checklist
 * on GitHub rather than against this site.
 */
function inlineHtml(markdown: string): string {
  const base = CHECKLIST_URL.replace("/blob/", "/tree/").replace(/[^/]+$/, "");
  return escapeHtml(markdown)
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/\*([^*]+)\*/g, "<em>$1</em>")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_m, text: string, href: string) => {
      const url = /^https?:/.test(href) ? href : base + href;
      return `<a href="${url}" target="_blank" rel="noreferrer">${text}</a>`;
    });
}

function kindTags(text: string): string[] {
  return [...text.matchAll(KIND_TAG)].map((m) => m[1]);
}

function headingTitle(text: string): string {
  return text.replace(KIND_TAG, "").replace(/\s+/g, " ").trim();
}

/**
 * Parses CHECKLIST.md: `## Track` → `### Section` → `- [ ] **Title** rest`.
 * An italic line under a heading is that heading's note. Section tags apply
 * to every line under them, so a filter on `build` finds all of Track B.
 */
async function loadChecklist(repoRoot: string): Promise<Checklist> {
  let markdown = "";
  try {
    markdown = await fs.readFile(path.resolve(repoRoot, CHECKLIST_PATH), "utf8");
  } catch {
    return { source: CHECKLIST_URL, tracks: [] };
  }

  const tracks: ChecklistTrack[] = [];
  let track: ChecklistTrack | undefined;
  let section: ChecklistSection | undefined;
  let trackTags: string[] = [];
  let sectionTags: string[] = [];
  let noteFor: { note: string } | undefined;
  let noteOpen = false;

  for (const line of markdown.split("\n")) {
    const trackMatch = /^## (Track (\w+).*)$/.exec(line);
    const sectionMatch = /^### ((\w+\d+).*)$/.exec(line);
    const itemMatch = /^- \[( |x)\] \*\*(.+?)\*\*(.*)$/.exec(line);
    const fieldMatch = /^\s{2,}- \*\*(.+?):\*\*\s*(.*)$/.exec(line);
    const lastItem = section?.items[section.items.length - 1];

    if (trackMatch) {
      trackTags = kindTags(trackMatch[1]);
      track = {
        id: trackMatch[2].toLowerCase(),
        title: headingTitle(trackMatch[1]),
        note: "",
        sections: [],
      };
      tracks.push(track);
      section = undefined;
      noteFor = track;
    } else if (sectionMatch && track) {
      sectionTags = [...trackTags, ...kindTags(sectionMatch[1])];
      section = {
        id: sectionMatch[2].toLowerCase(),
        title: headingTitle(sectionMatch[1]),
        note: "",
        items: [],
      };
      track.sections.push(section);
      noteFor = section;
    } else if (itemMatch && section) {
      const rest = itemMatch[3].replace(KIND_TAG, "").replace(/^\s*[:·]?\s*/, "");
      const title = itemMatch[2].replace(/:$/, "");
      section.items.push({
        done: itemMatch[1] === "x",
        title,
        rest: inlineHtml(rest),
        fields: [],
        tags: [...new Set([...sectionTags, ...kindTags(itemMatch[3])])],
      });
      noteFor = undefined;
    } else if (fieldMatch && lastItem) {
      lastItem.fields.push({ label: fieldMatch[1], html: inlineHtml(fieldMatch[2]) });
    } else if (noteFor && line.trim() !== "" && (noteOpen || /^\*[^*]/.test(line.trim()))) {
      // an italic note under a heading, possibly wrapped across lines
      const text = line.trim().replace(/^\*/, "");
      noteOpen = !text.endsWith("*");
      const html = inlineHtml(text.replace(/\*$/, ""));
      noteFor.note = noteFor.note ? `${noteFor.note} ${html}` : html;
      if (!noteOpen) noteFor = undefined;
    }
  }

  return { source: CHECKLIST_URL, tracks };
}

const RELEVANCE_ORDER: Record<Relevance, number> = {
  high: 0,
  medium: 1,
  low: 2,
};
const STATUS_ORDER: Record<PaperStatus, number> = {
  "to-read": 0,
  skimmed: 1,
  read: 2,
};

/**
 * Loads the site's three hand-kept data sources — the reading list, the
 * interactive pages, and blog front matter — and hands them to any page via
 * usePluginData("ocl-lab-data").
 */
/** Everything the plugin loads; the checklist is kept out of global data. */
type LoadedContent = LabData & { checklist: Checklist };

function summarizeChecklist(checklist: Checklist): LabsSummary {
  const tracks = checklist.tracks.map((t) => {
    const items = t.sections.flatMap((s) => s.items);
    return {
      id: t.id,
      title: t.title.replace(/^Track \w+ · /, "").replace(/\s*\(.*\)$/, ""),
      done: items.filter((i) => i.done).length,
      total: items.length,
    };
  });
  const solved = checklist.tracks
    .flatMap((t) => t.sections)
    .flatMap((s) =>
      s.items
        .filter((i) => i.done)
        .map((i) => ({
          title: i.title,
          href: /href="([^"]+)"/.exec(i.rest)?.[1],
          section: s.title.replace(/^\w+\d+ · /, ""),
        })),
    )
    .reverse();
  return {
    done: tracks.reduce((n, t) => n + t.done, 0),
    total: tracks.reduce((n, t) => n + t.total, 0),
    tracks,
    solved,
  };
}

export default async function labData(
  context: LoadContext,
  options: { blogDir?: string; routeBasePath?: string } = {},
): Promise<Plugin<LoadedContent>> {
  const { siteDir } = context;
  const dataDir = path.join(siteDir, "data");
  const repoRoot = path.resolve(siteDir, "..");
  const blogDir = path.resolve(siteDir, options.blogDir ?? "blog");
  const routeBasePath = options.routeBasePath ?? "writing";

  return {
    name: "ocl-lab-data",

    async loadContent(): Promise<LoadedContent> {
      const rawPapers =
        (await readYaml<Record<string, Omit<Paper, "id">>>(
          path.join(dataDir, "papers.yml"),
        )) ?? {};

      // Generated, never hand-edited: the record lives in the edit-slice repo and this
      // file is emitted from the same parse as the ledger page. Absent is not fatal —
      // a checkout without the generator having run should still build.
      const rawEvidence = await readYaml<Record<string, Omit<EvidenceRecord, "anchor">>>(
        path.join(dataDir, "evidence.yml"),
      ).catch(() => ({}) as Record<string, Omit<EvidenceRecord, "anchor">>);
      const evidence: EvidenceRecord[] = Object.entries(rawEvidence ?? {}).map(
        ([anchor, rec]) => ({ ...rec, anchor }),
      );

      const papers: Paper[] = Object.entries(rawPapers)
        .map(([id, paper]) => ({
          ...paper,
          id,
          projects: paper.projects ?? [],
          verified: paper.verified ?? false,
        }))
        .sort(
          (a, b) =>
            RELEVANCE_ORDER[a.relevance] - RELEVANCE_ORDER[b.relevance] ||
            STATUS_ORDER[a.status] - STATUS_ORDER[b.status] ||
            b.year - a.year,
        );

      const rawBuilt =
        (await readYaml<{
          built: {
            name: string;
            title: string;
            topic: string;
            what: string;
            from?: string;
            url?: string;
            /** Another entry's name: this card is a page inside that entry's copied folder. */
            in?: string;
            /** A file inside the folder other than index.html. */
            page?: string;
            added?: string;
            ratio?: number;
            image?: string;
          }[];
        }>(path.join(dataDir, "built.yml")))?.built ?? [];

      const byName = new Map(rawBuilt.map((entry) => [entry.name, entry]));
      const built: BuiltPage[] = rawBuilt.map((entry) => {
        // a card for one page of a folder another entry already copies
        const host = entry.in ? byName.get(entry.in) : entry;
        if (!host) throw new Error(`built.yml: ${entry.name} is "in" ${entry.in}, which isn't an entry`);
        const folder = `/demos/${host.name}/`;
        return {
          name: entry.name,
          title: entry.title,
          topic: entry.topic,
          what: entry.what.trim(),
          src: entry.url ?? folder + (entry.page ?? ""),
          external: Boolean(entry.url),
          origin: entry.url
            ? new URL(entry.url).host
            : (host.from ?? "").split("/").slice(0, -1).join("/") || "repo root",
          ratio: entry.ratio ?? 1.6,
          // js-yaml reads an unquoted date as a Date
          added: entry.added ? (entry.added as unknown instanceof Date ? (entry.added as unknown as Date).toISOString().slice(0, 10) : String(entry.added)) : undefined,
          // relative to the copied page's folder; a URL, or a path under static/ ("/img/..."), as is
          image: entry.image ? (/^(https?:|\/)/.test(entry.image) ? entry.image : folder + entry.image) : undefined,
        };
      });

      const rawProjects =
        (await readYaml<{
          projects: {
            name: string;
            plan: string;
            notebook: string;
            tone?: string;
            what?: string;
          }[];
        }>(path.join(dataDir, "projects.yml")))?.projects ?? [];

      // Absent is not fatal: a checkout without the file should still build, and the
      // page renders nothing rather than half of itself.
      const practice = await readYaml<Practice>(path.join(dataDir, "practice.yml"));

      const checklist = await loadChecklist(repoRoot);
      return {
        checklist,
        practice,
        labs: summarizeChecklist(checklist),
        writing: await loadWriting(blogDir, routeBasePath),
        builtAt: new Date().toISOString().slice(0, 10),
        papers,
        evidence,
        built,
        projects: await loadProjects(repoRoot, rawProjects),
      };
    },

    async contentLoaded({ content, actions }) {
      // Global data ships in the script every page loads; the checklist is
      // a few hundred KB, so it goes only to the route that renders it.
      const { checklist, ...global } = content;
      actions.setGlobalData(global);
      const data = await actions.createData("checklist.json", JSON.stringify(checklist));
      actions.addRoute({
        path: `${context.baseUrl}labs`,
        component: "@site/src/components/LabsPage.tsx",
        modules: { checklist: data },
        exact: true,
      });
    },
  };
}
