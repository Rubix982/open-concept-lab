#!/usr/bin/env python3
"""Bake the latest results into site/data/native.js for the web page.

    python3 export.py

Reads the newest results/bench-*.json (native Metal vs C, from ./bench) and,
if present, the newest results/browser-*.json (WebGPU vs JavaScript, from
browser-bench.mjs) and results/frames-*.json (recorded GPU playback, from
./bench --frames). Writes site/data/frames.js from the last, and
site/data/native.js as

    window.NATIVE_RESULTS = {"native": {...}, "browser": {...} or null};

A plain <script> tag loads it, so the page works opened straight from disk
(file://), where fetch() of a JSON file is blocked.
"""
import json
from datetime import date
from pathlib import Path

root = Path(__file__).resolve().parent.parent
results = root / "results"


def newest(pattern):
    files = sorted(results.glob(pattern))
    return json.loads(files[-1].read_text()) if files else None


native = newest("bench-*.json")
if native is None:
    raise SystemExit("no results/bench-*.json yet: run ./bench first")
out = {"native": native, "browser": newest("browser-*.json"), "exported": date.today().isoformat()}
target = root / "site" / "data" / "native.js"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(
    "// Generated by bench/export.py from results/*.json — don't edit by hand.\n"
    "window.NATIVE_RESULTS = " + json.dumps(out, indent=1) + ";\n"
)
print(f"wrote {target.relative_to(root)}" + ("" if out["browser"] else " (no browser results yet)"))

# recorded playback from ./bench --frames, if there is one
frames = newest("frames-*.json")
if frames:
    ft = root / "site" / "data" / "frames.js"
    ft.write_text(
        "// Generated by bench/export.py from results/frames-*.json (./bench --frames) — don't edit by hand.\n"
        "window.NATIVE_FRAMES = " + json.dumps(frames, separators=(",", ":")) + ";\n"
    )
    print(f"wrote {ft.relative_to(root)} ({ft.stat().st_size / 1e6:.1f} MB)")
else:
    print("no results/frames-*.json: run ./bench --frames for the page's recorded playback")
